function apply(rows, patches) {
  const out = rows.slice();
  for (const [r, c, piece] of patches) {
    const line = out[r].split('');
    for (let i = 0; i < piece.length; i++) line[c + i] = piece[i];
    out[r] = line.join('');
  }
  return out;
}

function mirror(rows) {
  return rows.map((r) => r.split('').reverse().join(''));
}

// --- Проверка ------------------------------------------------------------
function check(name, rows) {
  const bad = [];
  if (rows.length !== 40) bad.push(`строк ${rows.length}`);
  rows.forEach((r, i) => {
    if (r.length !== W) bad.push(`строка ${i}: ${r.length}`);
    for (const ch of r) {
      if (ch !== '.' && Number.isNaN(parseInt(ch, 36))) {
        bad.push(`строка ${i}: символ '${ch}'`);
      }
    }
  });
  if (bad.length) {
    console.error(`!! ${name}: ` + bad.slice(0, 6).join(', '));
    process.exitCode = 1;
  }
  return rows;
}

check('BASE', BASE);

const upLeft = check('upLeft', apply(apply(BASE, ARM_UP), ARM_IDLE));
const downLeft = check('downLeft', apply(apply(BASE, ARM_DOWN), ARM_IDLE));
const upRight = check('upRight', mirror(upLeft));
const downRight = check('downRight', mirror(downLeft));

function emit(name, rows) {
  let out = `  const ${name} = [\n`;
  for (const r of rows) out += `    '${r}',\n`;
  return out + '  ];\n\n';
}

const source =
  emit('TIGER_UP_LEFT', upLeft) +
  emit('TIGER_DOWN_LEFT', downLeft) +
  emit('TIGER_UP_RIGHT', upRight) +
  emit('TIGER_DOWN_RIGHT', downRight);

// Без --write просто печатает: удобно посмотреть глазами перед вставкой.
