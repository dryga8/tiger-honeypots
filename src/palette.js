// palette.js — палитра (раздел 2).
// Ни один цвет не задаётся в коде хардкодом — только отсюда.
//
// PALETTE_ORDER задаёт порядок ключей: индекс в этом массиве и есть тот
// «индекс палитры», которым в спрайтах кодируется цвет (раздел 10).
// Символ спрайта → индекс: parseInt(ch, 36), то есть '0'..'9' → 0..9,
// 'a'..'e' → 10..14. Точка '.' — прозрачность.
window.Game = window.Game || {};

(function (Game) {
  // Перечисление раздела 2 даёт 15 цветов, хотя в тексте названо число 14 —
  // см. «Отступления» в PROGRESS.md. Взят полный перечисленный набор.
  const PALETTE_ORDER = [
    'bg0',        // 0  тёмный фон
    'bg1',        // 1  фон чуть светлее (подложка поля)
    'wood0',      // 2  дерево: светлый тон (верхняя кромка желоба)
    'wood1',      // 3  дерево: основной тон
    'wood2',      // 4  дерево: тёмный тон (дно желоба, тень)
    'tigerBody',  // 5  тигр: основной рыжий
    'tigerDark',  // 6  тигр: тёмная обводка и полосы
    'tigerLight', // 7  тигр: светлое брюхо и морда
    'outline',    // 8  чёрный контур
    'white',      // 9  белый
    'green',      // a  корпус зелёного горшочка (светло-зелёный)
    'greenDark',  // b  тёмно-зелёный: обводка и детали
    'red',        // c  корпус красного горшочка (тёмно-красный)
    'redDark',    // d  тёмно-красный: обводка и детали
    'honey',      // e  жёлтый: мёд и сердца
  ];

  const palette = {
    bg0: '#12121c',
    bg1: '#1e1e2e',
    wood0: '#8a6a44',
    wood1: '#5a4632',
    wood2: '#33261b',
    tigerBody: '#e08a2b',
    tigerDark: '#6b3d0f',
    tigerLight: '#f2c48a',
    outline: '#0a0a0f',
    white: '#ffffff',
    green: '#7ed957',
    greenDark: '#2f7a2a',
    red: '#a8332a',
    redDark: '#5e1a15',
    honey: '#f2c81e',
  };

  // Готовый список цветов по индексу — чтобы отрисовка спрайта не дёргала
  // объект по ключу на каждый пиксель.
  const byIndex = PALETTE_ORDER.map((k) => palette[k]);

  Game.palette = palette;
  Game.PALETTE_ORDER = PALETTE_ORDER;
  Game.paletteByIndex = byIndex;
})(window.Game);
